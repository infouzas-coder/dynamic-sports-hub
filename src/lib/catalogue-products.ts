export function catalogueProducts(slug: string): CatalogueProduct[] {
  const key = slug.replace(/^\//, "");
  return (RAW[key] ?? [])
    .map(([code, name, file]) => ({
      code,
      name,
      image: IMAGES[`../assets/products/${key}/${file}`] ?? "",
    }))
    .filter((p) => p.image);
}
